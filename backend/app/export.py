"""Render a saved plan as a downloadable brief (Markdown or plain text)."""

from app import catalog
from app.rules import launch_group_text, page_counts_text, split_pages
from app.schemas import PlanInput, PlanResult


def _answers(inp: PlanInput) -> list[tuple[str, str]]:
    return [
        ("Business name", inp.business_name or "—"),
        ("Business type", catalog.BUSINESS_TYPES[inp.business_type]["label"]),
        ("Main goal", catalog.GOALS[inp.goal]["label"]),
        ("Audience", catalog.AUDIENCES[inp.audience]["label"]),
        ("Languages", ", ".join(catalog.LANGUAGES[x]["label"] for x in inp.languages)),
        ("Features picked", ", ".join(catalog.FEATURES[x]["label"] for x in inp.features) or "—"),
        ("Budget", catalog.BUDGETS[inp.budget]["label"]),
        ("Timeline", catalog.TIMELINES[inp.timeline]["label"]),
    ]


def render(plan_id: str, inp: PlanInput, plan: PlanResult, engine_version: str, markdown: bool) -> str:
    """One renderer for both formats; `markdown` only changes the formatting marks."""
    lines: list[str] = []

    def heading(level: int, text: str) -> None:
        if markdown:
            lines.extend(["#" * level + " " + text, ""])
        elif level == 3:
            lines.append(text)
        else:
            lines.extend([text.upper(), ("=" if level == 1 else "-") * len(text), ""])

    def bold(text: str) -> str:
        return f"**{text}**" if markdown else text

    title = inp.business_name or catalog.BUSINESS_TYPES[inp.business_type]["label"]
    heading(1, f"Website plan: {title}")
    lines += [f"Plan ID: {plan_id} · Generated by LaunchWise (rule engine v{engine_version})", ""]

    heading(2, "Summary")
    lines += [plan.summary, ""]

    heading(2, f"Site type: {plan.site_type.name}")
    lines += [plan.site_type.why, ""]

    c = plan.complexity
    weeks = "week" if c.estimated_weeks == "1" else "weeks"
    heading(2, f"Complexity: {c.score}/10 ({c.label}), about {c.estimated_weeks} {weeks}")
    lines += [c.why, ""]

    heading(2, "Sitemap")
    lines += [f"Pages: {page_counts_text(plan.sitemap)}.", ""]
    launch, required, later = split_pages(plan.sitemap)
    groups = [(f"Launch now: {launch_group_text(plan.sitemap)}", launch + required)]
    if later:
        groups.append((f"Later: {len(later)} page{'s' if len(later) != 1 else ''}", later))
    for label, pages in groups:
        heading(3, label)
        for p in pages:
            tag = " (required)" if p.required else ""
            lines.append(f"- {bold(p.name)}{tag} ({p.slug}): {', '.join(p.sections)}")
            lines.append(f"  Why: {p.why}")
        lines.append("")

    heading(2, "Features")
    for f in plan.features:
        tag = "must-have" if f.priority == "must" else "nice-to-have"
        if f.recommended:
            tag += ", recommended for you"
        lines.append(f"- {bold(f.name)} ({tag}): {f.why}")
    lines.append("")

    heading(2, "Content ideas")
    for block in plan.content_ideas:
        heading(3, block.page)
        lines += [f"- {idea}" for idea in block.ideas]
        lines.append("")

    heading(2, "SEO starter checklist")
    box = "- [ ] " if markdown else "[ ] "
    for item in plan.seo_checklist:
        lines.append(f"{box}{item.title} ({item.category}): {item.why}")
    lines.append("")

    heading(2, "Next steps")
    for i, step in enumerate(plan.next_steps, 1):
        lines.append(f"{i}. {step.title} {step.why}")
    lines.append("")

    heading(2, "Your answers")
    lines += [f"- {k}: {v}" for k, v in _answers(inp)]
    lines.append("")
    return "\n".join(lines)
